    select count(*) into v_n from storage.objects
     where bucket_id in ('payment-slips', 'consent-evidence');
    v_out := v_out || case when v_n = 0 then 'ok   anon storage.objects (private buckets): 0 rows'
                           else format('FAIL anon storage.objects (private buckets): %s rows visible', v_n) end || E'\n';
  exception when insufficient_privilege then
    v_out := v_out || 'ok   anon storage.objects: permission denied' || E'\n';
  end;

  foreach v_sql in array v_calls loop
    begin
      execute v_sql;
      v_out := v_out || format('FAIL anon call allowed: %s', v_sql) || E'\n';
    exception
      when insufficient_privilege then
        v_out := v_out || format('ok   anon call refused: %s', v_sql) || E'\n';
      when undefined_function then
        v_out := v_out || format('skip anon call (function not created yet): %s', v_sql) || E'\n';
      when others then
        v_out := v_out || format('FAIL anon call gave %s instead of 42501: %s', sqlstate, v_sql) || E'\n';
    end;
  end loop;

  perform set_config('cherrylee.smoke_anon', v_out, true);
end
$$;

