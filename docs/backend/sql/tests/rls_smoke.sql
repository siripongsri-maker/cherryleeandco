      else
        v_out := v_out || format('FAIL anon select %s: %s rows visible', v_rel, v_n) || E'\n';
      end if;
    exception
      when insufficient_privilege then
        v_out := v_out || format('ok   anon select %s: permission denied', v_rel) || E'\n';
      when undefined_table then
        v_out := v_out || format('skip anon select %s: not created yet', v_rel) || E'\n';
    end;
  end loop;

