-- =============================================================================
-- sql/tests/rls_smoke.sql · CherryLee & Co. backend · READ-ONLY SECURITY SMOKE CHECK
-- -----------------------------------------------------------------------------
-- What it checks (works after any number of migrations; missing tables are reported as "skip"):
--   Part A (static, from the catalogue): RLS is enabled on every table; anon has no table
--     privileges and cannot execute our functions; authenticated cannot execute service-only
--     functions or touch child_health / rate_limit_events; no policy targets anon/public;
--     buckets are private; every SECURITY DEFINER function pins search_path; views are
--     security_invoker; the pg_cron jobs exist.
--   Part B (live, as role anon): every table/view returns permission denied or 0 rows;
--     every function call is refused.
--   Part C (live, as a signed-in user WITHOUT a staff role): same expectations.
-- How to run: ONLY by the builder (never an implementer), with the user's OK:
--   paste it into Lovable → More → Cloud → SQL editor (review R-19: the editor runs it once and never saves
--   it as a migration), or in a local Supabase (supabase start). Never through Lovable chat (the agent may
--   store it as a migration) and never through MCP query_database writes.
-- Safety: it inserts NO test data. Everything runs inside BEGIN … ROLLBACK, so even a security
--   bug that let a call through leaves nothing behind.
-- Not checkable in SQL (do it by hand at every G10, 40-integrations § 13): Cloud → Users → Auth settings shows
--   public sign-up DISABLED. If sign-up were on, anyone could become a "no-role" user (Part C).
-- Reading the result: one table with columns (part, line). Lines starting with "FAIL" are
--   security bugs → stop and report. "REVIEW" = a function that isn't ours is callable by anon
--   (probably generated by Lovable) → tell the builder. "ok"/"skip" are fine.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- Part B · live checks as anon (results collected in a transaction-local setting)
-- -----------------------------------------------------------------------------
select set_config('request.jwt.claims', '{"role":"anon"}', true);
